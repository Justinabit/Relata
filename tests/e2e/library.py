"""Library roundtrip, invalid imports, storage failure and mobile keyboard controls."""
import os, json
from playwright.sync_api import sync_playwright, expect
from seen import SEEN
BASE = os.environ.get('BASE_URL', 'http://localhost:8790')
with sync_playwright() as p:
    browser = p.chromium.connect_over_cdp(os.environ['BROWSER_CDP_URL']) if os.environ.get('BROWSER_CDP_URL') else p.chromium.launch()
    ctx = browser.new_context(accept_downloads=True, viewport={'width': 360, 'height': 800})
    ctx.add_init_script(SEEN)
    page = ctx.new_page()
    page.goto(BASE + '/app')
    page.locator('textarea').fill('Learning technology')
    page.get_by_role('button', name='Analyze Topic').click()
    expect(page.locator('article.study').first).to_be_visible()
    page.locator('article.study').first.get_by_role('button', name='Save', exact=True).click()
    page.goto(BASE + '/app/library')
    expect(page.locator('article.study')).to_have_count(1)
    page.get_by_label('Filter saved studies').fill('no matching title')
    expect(page.locator('article.study')).to_have_count(0)
    page.get_by_label('Filter saved studies').fill('')
    page.get_by_label('Sort saved studies').select_option('title')
    with page.expect_download() as download:
        page.get_by_role('button', name='Export library JSON').click()
    path = download.value.path()
    original = json.load(open(path))
    page.get_by_label('Import library JSON', exact=True).set_input_files(path)
    expect(page.get_by_role('status').filter(has_text='Library imported')).to_be_visible()
    expect(page.locator('article.study')).to_have_count(1)
    page.get_by_label('Import library JSON', exact=True).set_input_files({'name':'bad.json','mimeType':'application/json','buffer':b'{"version":9}'})
    expect(page.get_by_role('status').filter(has_text='not a valid Relata library')).to_be_visible()
    page.locator('article.study').get_by_role('button', name='Saved', exact=True).click()
    expect(page.locator('article.study')).to_have_count(0)
    page.get_by_label('Import library JSON', exact=True).set_input_files(path)
    expect(page.locator('article.study')).to_have_count(1)
    page.get_by_role('button', name='More details').click()
    page.get_by_role('button', name='Remove from library', exact=True).focus()
    page.keyboard.press('Enter')
    expect(page.locator('article.study')).to_have_count(0)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    ctx.close()
    ctx = browser.new_context()
    ctx.add_init_script("Storage.prototype.getItem=()=>{throw Error('blocked')};Storage.prototype.setItem=()=>{throw Error('blocked')};")
    page = ctx.new_page(); page.goto(BASE + '/app/library')
    expect(page.get_by_text('Your browser blocked saving')).to_be_visible()
    ctx.close()
    print('PASS library import/export, validation, remove, keyboard, mobile and blocked storage')
